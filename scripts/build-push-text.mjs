// Bundles src/features/inbox/pushText.ts for the ingest Edge Function
// (Deno can't resolve the app's '@/...' imports nor extensionless paths).
// The output is committed: `supabase functions deploy ingest` ships it as is.
// Re-run after touching the parser or the inbox.push* texts:
//   npm run build:push-text
// pushText.test.ts fails if the committed bundle answers differently from the source.
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

export async function bundlePushText() {
  const out = await build({
    entryPoints: [`${root}src/features/inbox/pushText.ts`],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    write: false,
    alias: { '@': `${root}src` },
    legalComments: 'none',
  });
  const banner = '// GENERATED by scripts/build-push-text.mjs from src/features/inbox/pushText.ts. Do not edit.\n';
  return banner + out.outputFiles[0].text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { writeFileSync } = await import('node:fs');
  writeFileSync(`${root}supabase/functions/ingest/pushText.gen.js`, await bundlePushText());
  console.log('supabase/functions/ingest/pushText.gen.js');
}
